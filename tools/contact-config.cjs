/**
 * Writes the contact form's delivery configuration from the environment.
 *
 * The form is static HTML, so it cannot read an environment variable at runtime.
 * The key is read here and baked into `public/contact/config.js` on every
 * `npm start` and `npm run build`, so the build — not the browser — assembles
 * it.
 *
 * Sources, highest priority first:
 *
 * 1. `WEB3FORMS_ACCESS_KEY` in the process environment — what CI passes in, and
 *    what overrides everything else.
 * 2. `.env.local` — a developer's local override. Gitignored, so a clone can
 *    point the form at its own key without touching the tracked file.
 * 3. `.env` — the project's own env file. Tracked, so a plain `npm run build`
 *    carries the key and CI needs no secret configured anywhere.
 *
 * Two honest caveats, both true of every static host:
 *
 * 1. The key still ships to the browser. A Web3Forms access key is designed for
 *    that — it can only route mail to its owner's inbox — but it is not a secret
 *    once the page is deployed, and nobody should treat it as one.
 * 2. With no key configured the file is written with an empty one, and the form
 *    falls back to `mailto:` instead of posting a request that would be rejected.
 *
 * The output file is always written, even when the key is missing, because a 404
 * for a `<script>` is a console error — and the audit treats a console error as
 * a failure.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'public', 'contact', 'config.js');
const ENDPOINT = 'https://api.web3forms.com/submit';

/** Reads `KEY=value` lines from one env file without pulling in a dependency. */
function readEnvFile(name) {
  const file = path.join(ROOT, name);
  if (!fs.existsSync(file)) return {};

  const values = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (/^\s*#/.test(line)) continue;
    const match = /^\s*([A-Za-z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    values[match[1]] = match[2].trim().replace(/^['"]|['"]$/g, '');
  }
  return values;
}

const fromProcess = (process.env['WEB3FORMS_ACCESS_KEY'] || '').trim();
const fromLocal = (readEnvFile('.env.local')['WEB3FORMS_ACCESS_KEY'] || '').trim();
const fromProject = (readEnvFile('.env')['WEB3FORMS_ACCESS_KEY'] || '').trim();

const accessKey = fromProcess || fromLocal || fromProject;
const source = fromProcess
  ? 'the process environment'
  : fromLocal
    ? '.env.local'
    : fromProject
      ? '.env'
      : '';

const contents = `/* Generated by tools/contact-config.cjs. Not committed — do not edit. */
window.DEEPWORK_CONTACT = {
  endpoint: ${accessKey ? `'${ENDPOINT}'` : "''"},
  accessKey: '${accessKey}',
  provider: 'Web3Forms',
  /* hCaptcha is enforced on this Web3Forms form, so a token is mandatory.
     Set this to false if the dashboard ever turns that check off. */
  captcha: ${accessKey ? 'true' : 'false'},
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, contents, 'utf8');

if (accessKey) {
  console.log(`contact form: Web3Forms configured from ${source}`);
} else {
  console.log(
    "contact form: no WEB3FORMS_ACCESS_KEY — the form will fall back to opening the visitor's mail app",
  );
}
